#!/usr/bin/env python3
"""Hermetic acceptance-tool tests; never install, launch, or change security state."""
import copy
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

sys.dont_write_bytecode = True

ROOT = Path(__file__).resolve().parent.parent
SPEC = importlib.util.spec_from_file_location("acceptance", ROOT / "scripts/release-acceptance.py")
MODULE = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(MODULE)


def fixture():
    tag, version, sha = "v1.2.3", "1.2.3", "a" * 64
    repository = "https://github.com/VincentShipsIt/macsweep.dev"
    names = [f"macsweep-{tag}-macos.zip", f"macsweep-{tag}-macos.zip.sha256", f"macsweep-{tag}.tar.gz.sha256"]
    return {
        "release": {"tag_name": tag, "draft": False, "prerelease": False, "published_at": "2026-01-01T00:00:00Z",
                    "html_url": f"{repository}/releases/tag/{tag}",
                    "body": "# MacSweep 1.2.3\n\n## GUI scope\nNative macOS 26 app.\n\n## Deferred features\niOS companion.\n",
                    "assets": [{"name": name, "state": "uploaded", "digest": f"sha256:{sha}",
                                "browser_download_url": f"{repository}/releases/download/{tag}/{name}"} for name in names]},
        "cask": {"casks": [{"version": version, "sha256": sha,
                            "url": f"{repository}/releases/download/{tag}/macsweep-{tag}-macos.zip",
                            "depends_on": {"formula": [MODULE.TAP]},
                            "artifacts": [{"app": ["MacSweep.app"]}, {"binary": ["/opt/macsweep/bin/macsweep"]}]}]},
        "formula": {"formulae": [{"versions": {"stable": version}, "urls": {"stable": {
            "url": f"{repository}/archive/refs/tags/{tag}.tar.gz", "checksum": sha}}}]},
        "swift": 'public static let current = "1.2.3"',
        "pbx": "MARKETING_VERSION = 1.2.3;\nCURRENT_PROJECT_VERSION = 1.2.3;\n" * 2,
        "app_sha": sha + "\n", "source_sha": sha + "\n"}


class ReleaseAcceptanceTests(unittest.TestCase):
    def test_aligned_release_has_a_content_addressed_receipt(self):
        result = MODULE.validate(fixture())
        self.assertTrue(result["metadataAligned"])
        self.assertEqual(result["version"], "1.2.3")
        self.assertEqual(len(result["releaseNotesSHA256"]), 64)

    def test_historical_repository_alias_requires_the_same_exact_tag_and_digest(self):
        data = fixture()
        data["formula"]["formulae"][0]["urls"]["stable"]["url"] = (
            "https://github.com/VincentShipsIt/macsweep/archive/refs/tags/v1.2.3.tar.gz")
        self.assertTrue(MODULE.validate(data)["historicalRepositoryAlias"])
        data["formula"]["formulae"][0]["urls"]["stable"]["checksum"] = "b" * 64
        with self.assertRaises(ValueError): MODULE.validate(data)

    def test_version_tag_and_source_drift_fail(self):
        for key, value in (("swift", 'static let current = "1.2.4"'),
                           ("pbx", "MARKETING_VERSION = 1.2.3; CURRENT_PROJECT_VERSION = 1.2.4;")):
            data = fixture(); data[key] = value
            with self.subTest(key=key), self.assertRaises(ValueError): MODULE.validate(data)
        for tag in ("nightly", "v1.2", "v1.2.3; echo unsafe"):
            data = fixture(); data["release"]["tag_name"] = tag
            with self.subTest(tag=tag), self.assertRaises(ValueError): MODULE.validate(data)

    def test_cask_and_formula_artifact_drift_fail(self):
        mutations = [lambda d: d["cask"]["casks"][0].update(version="1.2.4"),
                     lambda d: d["cask"]["casks"][0].update(sha256="b" * 64),
                     lambda d: d["cask"]["casks"][0].update(artifacts=[]),
                     lambda d: d["cask"]["casks"][0].update(depends_on={}),
                     lambda d: d["formula"]["formulae"][0]["urls"]["stable"].update(url="https://example.invalid/source"),
                     lambda d: d["formula"]["formulae"][0]["urls"]["stable"].update(checksum="b" * 64)]
        for mutation in mutations:
            data = fixture(); mutation(data)
            with self.subTest(data=data), self.assertRaises(ValueError): MODULE.validate(data)

    def test_release_notes_must_state_current_gui_and_deferred_scope(self):
        for body in ("Only autogenerated changes", "## GUI scope\nNative macOS 26 v1.2.3.",
                     "## GUI scope\nNative macOS 26.\n## Deferred features\niOS."):
            data = fixture(); data["release"]["body"] = body
            with self.subTest(body=body), self.assertRaises(ValueError): MODULE.validate(data)
        MODULE.validate_notes((ROOT / "docs/releases/v1.1.4.md").read_text(), "1.1.4")

    def test_unpublished_missing_duplicate_or_modified_assets_fail(self):
        mutations = [lambda d: d["release"].update(draft=True),
                     lambda d: d["release"].update(prerelease=True),
                     lambda d: d["release"]["assets"].pop(),
                     lambda d: d["release"]["assets"].append(copy.deepcopy(d["release"]["assets"][0])),
                     lambda d: d["release"]["assets"][0].update(digest="sha256:" + "b" * 64),
                     lambda d: d.update(app_sha="<html>not a digest</html>")]
        for mutation in mutations:
            data = fixture(); mutation(data)
            with self.subTest(data=data), self.assertRaises(ValueError): MODULE.validate(data)

    def test_install_script_refuses_a_non_runner_before_any_mutation(self):
        result = subprocess.run(["bash", str(ROOT / "scripts/fresh-install-acceptance.sh")],
                                env={"PATH": os.environ["PATH"]}, capture_output=True, text=True, check=False)
        self.assertEqual(result.returncode, 2)
        self.assertIn("requires a GitHub-hosted macOS runner", result.stderr)

    def run_freshness(self, casks=(0, "", ""), formulae=(0, "", ""), processes=(1, "", "")):
        results = {("brew", "list", "--cask", "--versions"): casks,
                   ("brew", "list", "--formula", "--versions"): formulae,
                   ("pgrep", "-x", "MacSweep"): processes}
        def native(command, **options):
            status, stdout, stderr = results[tuple(command)]
            self.assertEqual(options["timeout"], 30)
            return subprocess.CompletedProcess(command, status, stdout, stderr)
        scratch = ROOT / ".tmp"
        scratch.mkdir(exist_ok=True)
        with tempfile.TemporaryDirectory(dir=scratch) as temporary:
            directory = Path(temporary)
            try:
                receipt = MODULE.freshness(directory, run=native)
                return receipt, None, {path.name: path.read_text() for path in directory.iterdir()}
            except ValueError as error:
                return None, str(error), {path.name: path.read_text() for path in directory.iterdir()}

    def test_successful_full_inventories_match_only_exact_package_tokens(self):
        receipt, error, raw = self.run_freshness(
            casks=(0, "macsweeper 1.2.3\n", ""), formulae=(0, "macsweep-cli 1.2.3\nother 4.5.6\n", ""))
        self.assertIsNone(error)
        self.assertTrue(receipt["nativeInventoriesSucceeded"])
        self.assertEqual(raw["preexisting-casks.txt"], "macsweeper 1.2.3\n")
        self.assertEqual(json.loads(raw["freshness-command-status.json"])["processes"]["exitStatus"], 1)
        for token in ("macsweep", MODULE.TAP):
            for category in ("casks", "formulae"):
                receipt, error, _ = self.run_freshness(**{category: (0, token + " 1.1.4\n", "")})
                with self.subTest(token=token, category=category):
                    self.assertIsNone(receipt)
                    self.assertIn("already installed", error)

    def test_failed_or_malformed_package_inspection_never_means_absent(self):
        for category in ("casks", "formulae"):
            for status in (1, 2, 126):
                receipt, error, raw = self.run_freshness(**{category: (status, "", "inspection denied\n")})
                with self.subTest(category=category, status=status):
                    self.assertIsNone(receipt)
                    self.assertIn("freshness is unknown", error)
                    self.assertEqual(raw[f"preexisting-{category}-stderr.txt"], "inspection denied\n")
            receipt, error, _ = self.run_freshness(**{category: (0, "unparseable\n", "")})
            self.assertIsNone(receipt)
            self.assertIn("Malformed", error)

    def test_process_absence_requires_exit_one_without_diagnostics(self):
        receipt, error, _ = self.run_freshness(processes=(1, "", ""))
        self.assertIsNone(error)
        self.assertTrue(receipt["processAbsent"])
        for status, stdout, stderr in ((0, "1234\n", ""), (2, "", "inspection failed\n"),
                                       (-9, "", ""), (1, "", "unexpected diagnostic\n")):
            receipt, error, raw = self.run_freshness(processes=(status, stdout, stderr))
            with self.subTest(status=status, stderr=stderr):
                self.assertIsNone(receipt)
                self.assertIsNotNone(error)
                self.assertEqual(raw["preexisting-processes-stderr.txt"], stderr)

    def test_installed_gui_cli_and_package_versions_must_all_align(self):
        data = {"version": "1.2.3", "app_version": "1.2.3\n", "app_build": "1.2.3\n",
                "app_id": "dev.macsweep.app\n", "cli_version": "macsweep.dev 1.2.3\n",
                "cask": {"casks": [{"installed": "1.2.3"}]},
                "formula": {"formulae": [{"installed": [{"version": "1.2.3"}]}]}}
        self.assertTrue(MODULE.validate_installed(data)["appAndCLIAligned"])
        for key in ("app_version", "app_build", "app_id", "cli_version"):
            changed = copy.deepcopy(data); changed[key] = "unexpected 1.2.3 output"
            with self.subTest(key=key), self.assertRaises(ValueError): MODULE.validate_installed(changed)
        for key, rows in (("cask", {"casks": [{"installed": "1.2.4"}]}),
                          ("formula", {"formulae": [{"installed": []}]})):
            changed = copy.deepcopy(data); changed[key] = rows
            with self.subTest(key=key), self.assertRaises(ValueError): MODULE.validate_installed(changed)


if __name__ == "__main__":
    unittest.main(verbosity=2)
